// ============================================================
// Qora — Legacy bundler (rebuilt for the Qora-only repo)
// ------------------------------------------------------------
// Concatenates the Qora source files (UNCHANGED, byte-for-byte) in the
// exact order the app expects, into a single ES-module entry
// (src/main.jsx) that Vite can build for production.
//
// Why concatenate instead of refactor to imports:
//   The Qora screens run in ONE shared global scope (originally
//   Babel-standalone + classic <script> tags). Every top-level
//   identifier is unique, so a single shared module scope reproduces the
//   exact same runtime behaviour — zero changes to design or logic.
//
// After the OphthaSim cleanup (commit 2f5ba98) only the Qora files
// survive; the OphthaSim data/engine/component files were removed. This
// LOAD_ORDER reflects the surviving Qora-only set.
// ============================================================

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Load order for the Qora-only app. data-store.js must come first (it
// exposes window.ApiDataStore, which qora-landing.jsx calls at auth time).
const LOAD_ORDER = [
  'engine/data-store.js',
  'qora-catalog.js',
  'translations.js',
  'qora-landing.jsx',
  'qora-v2.jsx',
  'qora-pf.jsx',
  'qora-enhancements.jsx',
];

const HTML_FILE = 'Virtual Patient Simulator.html';

function extractInlineApp(html) {
  // The src-loaded scripts are `<script type="text/babel" src="...">`.
  // The single inline App script is `<script type="text/babel">` (no src),
  // so this pattern matches ONLY the inline block.
  const m = html.match(/<script type="text\/babel">\n?([\s\S]*?)<\/script>/);
  if (!m) throw new Error('Could not locate the inline App <script> block in ' + HTML_FILE);
  return m[1];
}

const header = `// AUTO-GENERATED by build/bundle-legacy.mjs — DO NOT EDIT THIS FILE.
// Edit the original .js / .jsx source files instead; this is just a build
// artifact that re-creates the app's single shared scope for Vite.
import React from 'react';
import * as ReactDOM from 'react-dom/client';
import confetti from 'canvas-confetti';
import '../design.css';

// The original code calls window.confetti(...) directly.
window.confetti = confetti;

// Backend base URL from Vite env. Empty -> same-origin relative calls
// (works when FastAPI serves the built SPA). Set VITE_API_BASE for a
// cross-origin dev backend (e.g. http://localhost:8000).
window.OPHTHA_API_BASE = import.meta.env.VITE_API_BASE || '';

// Google Sign-In client id (empty -> the Google button stays disabled).
window.QORA_GOOGLE_CLIENT_ID = import.meta.env.VITE_GOOGLE_CLIENT_ID || '';
`;

const parts = [header];

for (const rel of LOAD_ORDER) {
  const abs = join(ROOT, rel);
  if (!existsSync(abs)) throw new Error('Missing source file: ' + rel);
  const code = readFileSync(abs, 'utf8');
  parts.push(`\n// ===== BEGIN ${rel} =====\n`);
  parts.push(code);
  parts.push(`\n// ===== END ${rel} =====\n`);
}

const html = readFileSync(join(ROOT, HTML_FILE), 'utf8');
parts.push(`\n// ===== BEGIN inline App (from ${HTML_FILE}) =====\n`);
parts.push(extractInlineApp(html));
parts.push(`\n// ===== END inline App =====\n`);

const outDir = join(ROOT, 'src');
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'main.jsx');
writeFileSync(outFile, parts.join(''), 'utf8');

console.log(`[bundle-legacy] Wrote ${outFile} from ${LOAD_ORDER.length} source files + inline App.`);
